-- 告警的第二种方向证据：该分钟主动净买额（元）。
--
-- 为什么需要第二列：
--   量能类告警的方向优先看价格涨跌幅，但「分钟内实时爆量」在第 9~40 秒就判定，
--   此时价格常常一动没动（实测近 200 条里约 40% 涨跌幅为 0.00%），
--   只剩成交量倍数，卡片就无法区分是放量拉升还是放量砸盘。
--   这类时点主动净买额已经在毫秒级通道里算好了，用它兜底，
--   既不需要猜方向，也和平台「红=资金流入、绿=资金流出」的口径一致。
--
-- 资金类指标与「分钟量能突变（定稿）」这一列留空：
--   前者方向看 value 正负；后者拿不到净额，价格涨跌幅已经足够。
ALTER TABLE alert ADD COLUMN net_flow REAL;
